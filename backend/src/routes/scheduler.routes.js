import { requireAuth, requireRole, loadOwnProfile } from '../middleware/auth.js';
import { validateBody } from '../middleware/validate.js';
import { asyncHandler } from '../middleware/errorHandler.js';
import { idempotency } from '../middleware/idempotency.js';
import { generateProposals, buildFeasibleSpace, SLOT_WEIGHTS } from '../services/scheduling.service.js';
import { rankInterviewers, MATCH_WEIGHTS } from '../services/matching.service.js';
import { confirmProposal } from '../services/orchestration.service.js';
import { callAiService } from '../providers/aiClient.js';
import { auditFromRequest } from '../services/audit.service.js';
import { parseArray, stringifyJson } from '../lib/json.js';
import { badRequest, notFound, forbidden } from '../lib/errors.js';
